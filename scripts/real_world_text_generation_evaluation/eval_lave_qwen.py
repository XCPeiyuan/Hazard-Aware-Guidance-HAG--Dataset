#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
对 review-danger-correct.txt 中的项目进行 LAVE 评估。
新增：
  - tqdm 进度条
  - 打印模型 raw 输出，便于监控
  - 更严格的 JSON 校验 + 重试
"""

import os
import re
import json
from typing import List, Tuple, Dict, Any

import torch
from tqdm import tqdm
from transformers import AutoModelForCausalLM, AutoTokenizer

import os
os.environ["CUDA_VISIBLE_DEVICES"] = "2"
# ================== 配置 ==================
REF_TXT = "test_R_en.txt"
REVIEW_TXT = "/carrot/zhup/[main]inference/Prompt-only/qwen25vl32b/r-0shot/review-danger-correct.txt"
MODEL_NAME = "Qwen/Qwen3-14B"

OUTPUT_JSON = os.path.join(os.path.dirname(REVIEW_TXT),
                           "review-danger-correct_scores.json")

MAX_RETRY = 3
MAX_NEW_TOKENS = 2048
# =========================================


def parse_triplet_txt(path: str) -> List[Tuple[str, str]]:
    items = []
    with open(path, "r", encoding="utf-8") as f:
        lines = [ln.rstrip("\n") for ln in f]

    i, n = 0, len(lines)
    while i < n:
        while i < n and lines[i].strip() == "":
            i += 1
        if i >= n:
            break
        img = lines[i].strip()
        i += 1
        content = ""
        if i < n:
            content = lines[i].strip()
            i += 1
        while i < n and lines[i].strip() == "":
            i += 1
        if img:
            items.append((img, content))
    return items


def extract_tag(text: str, tag: str) -> str:
    m = re.search(rf"<{tag}>(.*?)</{tag}>", text, flags=re.S | re.I)
    return m.group(1).strip() if m else ""


def build_prompt(ref_alert, ref_guide, pred_alert, pred_guide) -> str:
    prompt = f"""
You are an expert evaluator for textual guidance for blind pedestrians.

You will be given:
1) A REFERENCE answer written by a human expert.
2) A MODEL answer generated by another model.

You must evaluate ONLY the MODEL answer, based on comparison with the REFERENCE.
The model cannot see the image.

### Scoring Rules (0–10 integers only):

1. hazard_score:
   Evaluate MODEL_ALERT vs REFERENCE_ALERT:
   - Does the MODEL cover the main hazards mentioned in the reference?
   - Are the directions and distances reasonable?
   Ignore any extra hazards mentioned by the model.

2. guide_score:
   Evaluate MODEL_GUIDE vs REFERENCE_GUIDE:
   - Correctness (should remain safe)
   - Specificity (left/right, distance, steps)
   - Executability (blind person can follow)
   Do NOT penalize lack of conciseness.

3. format_score:
   Ignore <ALERT> and <GUIDE> tags.
   Check inner content only:
   - No extra labels/explanations
   - Understandable & clean language
   - Missing 'be' verbs is OK.

4. overall_score:
   Weighted combination, prioritizing hazard_score and guide_score.

Output REQUIREMENTS:
- ONE LINE of valid JSON.
- Must contain:
  "hazard_score", "guide_score", "format_score", "overall_score", "comment"
- All scores must be integers 0–10.

Now evaluate the following sample.

[REFERENCE_ALERT]
{ref_alert}

[REFERENCE_GUIDE]
{ref_guide}

[MODEL_ALERT]
{pred_alert}

[MODEL_GUIDE]
{pred_guide}

Respond with ONE LINE of JSON only.
"""
    return prompt.strip()


def load_model_and_tokenizer(model_name: str):
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        torch_dtype="auto",
        device_map="auto"
    )
    return tokenizer, model


def call_model_once(tokenizer, model, prompt: str) -> str:
    messages = [{"role": "user", "content": prompt}]
    text = tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True, enable_thinking=True
    )
    inputs = tokenizer([text], return_tensors="pt").to(model.device)

    with torch.no_grad():
        outputs = model.generate(
            **inputs, 
            max_new_tokens=MAX_NEW_TOKENS
        )

    # Extract new tokens only
    output_ids = outputs[0][len(inputs.input_ids[0]):].tolist()

    # Remove <think> part using </think> token id = 151668
    THINK_END = 151668
    try:
        idx = len(output_ids) - 1 - output_ids[::-1].index(THINK_END)
        content_ids = output_ids[idx:]
    except ValueError:
        content_ids = output_ids

    content = tokenizer.decode(content_ids, skip_special_tokens=True).strip()
    return content


def try_parse_json(raw: str) -> Dict[str, Any] | None:
    # Extract the substring between the first "{" and last "}"
    s = raw.find("{")
    e = raw.rfind("}")
    if s == -1 or e == -1 or e <= s:
        return None

    json_str = raw[s:e + 1]

    try:
        data = json.loads(json_str)
    except Exception:
        return None

    required = ["hazard_score", "guide_score", "format_score", "overall_score", "comment"]
    if not all(k in data for k in required):
        return None

    # Validate score types & ranges
    for k in required[:-1]:
        v = data[k]
        try:
            v = int(v)
        except:
            return None
        if not (0 <= v <= 10):
            return None
        data[k] = v

    # ensure comment is str
    data["comment"] = str(data["comment"])

    return data


def main():
    # Load reference dataset
    ref_items = parse_triplet_txt(REF_TXT)
    ref_dict = {img: text for img, text in ref_items}

    # Load review samples
    review_items = parse_triplet_txt(REVIEW_TXT)

    print(f"Loading model {MODEL_NAME} ...")
    tokenizer, model = load_model_and_tokenizer(MODEL_NAME)
    print("Model loaded!")

    results = []

    for img, pred_text in tqdm(review_items, desc="Evaluating", ncols=100):
        if img not in ref_dict:
            print(f"\n[WARN] Reference not found for {img}, skipped.")
            continue

        ref_text = ref_dict[img]

        # Extract tags
        ref_alert = extract_tag(ref_text, "ALERT")
        ref_guide = extract_tag(ref_text, "GUIDE")
        pred_alert = extract_tag(pred_text, "ALERT")
        pred_guide = extract_tag(pred_text, "GUIDE")

        # Build prompt
        prompt = build_prompt(ref_alert, ref_guide, pred_alert, pred_guide)

        scores = None
        for retry in range(MAX_RETRY):
            raw = call_model_once(tokenizer, model, prompt)

            print("\n---------------- RAW OUTPUT ----------------")
            print(raw)
            print("--------------------------------------------\n")

            scores = try_parse_json(raw)
            if scores is not None:
                break
            print(f"[Retry {retry+1}/{MAX_RETRY}] Invalid JSON, retrying...")

        if scores is None:
            print(f"[ERROR] Could not parse scores for {img}. Skipping.\n")
            continue

        print(f"[RESULT] {img}  hazard={scores['hazard_score']} "
              f"guide={scores['guide_score']} format={scores['format_score']} "
              f"overall={scores['overall_score']}\n")

        results.append({
            "image": img,
            "ref_alert": ref_alert,
            "ref_guide": ref_guide,
            "pred_alert": pred_alert,
            "pred_guide": pred_guide,
            "scores": scores
        })

    # Save to JSON
    with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)

    print("\n============================================")
    print(f"Saved {len(results)} evaluated samples to:")
    print(OUTPUT_JSON)
    print("============================================\n")


if __name__ == "__main__":
    main()

